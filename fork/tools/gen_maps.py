def tests_map():
    out = ["# 测试地图\n\n", NOTICE]
    out.append("仓库有三棵测试树，没有一个命令同时运行全部测试。fork 不修改 `tests/`（它与上游逐字节一致）。\n\n")
    rows = [
        [tick("tests/"), "上游 pytest"],
        [tick("csrc/src/testing/"), "上游 C++（Catch2/CTest）与服务端 Python"],
    ] + [[tick(tree), note] for tree, note in FORK_TEST_TREES.items()]
    for f in FILES:
        stray = f.startswith("fork/") and not f.startswith(tuple(FORK_TEST_TREES))
        if stray and re.fullmatch(r"test_.*\.py", Path(f).name):
            ERRORS.append(f"{f}: fork test outside FORK_TEST_TREES; add its tree there in fork/tools/gen_maps.py")
    out += ["## 测试树\n\n", table(["位置", "内容"], rows), "\n"]
    out.append("运行它们的命令见 [build-and-release.md 的“测试命令”](../build-and-release.md#测试命令)。\n\n")

    markers = re.findall(r'addinivalue_line\(\s*"markers",\s*"([^"]+)"', required("tests/conftest.py"))
    out.append("## pytest 标记\n\n")
    out.append("定义在 `tests/conftest.py`。`--no-gpu` 跳过 gpu 用例，`--slow` 才运行 slow 用例。\n\n")
    out += ["".join(f"- `{m.split(':')[0]}`：{m.split(':', 1)[1].strip()}\n" for m in markers), "\n"]

    py_tests = [f for f in FILES if f.startswith("tests/") and Path(f).name.startswith("test_") and f.endswith(".py")]
    groups = defaultdict(list)
    for f in py_tests:
        groups["/".join(f.split("/")[:2]) if f.count("/") >= 2 else "tests"].append(f)
    rows = []
    for group in sorted(groups):
        files = groups[group]
        gpu = sum(bool(re.search(r"pytest\.mark\.gpu|pytestmark\s*=.*\bgpu\b", text(f))) for f in files)
        slow = sum(bool(re.search(r"pytest\.mark\.slow|pytestmark\s*=.*\bslow\b", text(f))) for f in files)
        rows.append([tick(group + "/" if group != "tests" else "tests/*.py"), len(files), gpu, slow])
    out.append("## `tests/` 各目录\n\n")
    out.append("gpu、slow 两列是含相应标记的测试文件数。\n\n")
    out += [table(["目录", "测试文件", "gpu", "slow"], rows), "\n"]

    serve_py = [f for f in FILES if f.startswith("csrc/src/testing/serve/") and f.endswith(".py")]
    runners = [
        f
        for f in FILES
        if (
            f in ("Makefile", "pyproject.toml", "fork/dev", "fork/tools/test_cpu.sh")
            or f.startswith(".github/workflows/")
        )
        and "csrc/src/testing/serve" in text(f)
    ]
    out.append("## `csrc/src/testing/serve` 中的 Python 文件\n\n")
    upstream = [tick(r) for r in runners if not r.startswith("fork/")]
    fork = [tick(r) for r in runners if r.startswith("fork/")]
    out.append(
        f"共 {len(serve_py)} 个。提到这个目录的上游运行入口（Makefile、pyproject.toml、工作流）："
        + ("、".join(upstream) or "无")
        + "；fork 的运行入口："
        + ("、".join(fork) or "无")
        + "。\n\n"
    )
    out += ["".join(f"- `{f}`\n" for f in serve_py)]
    return "".join(out)


# ---------------------------------------------------------------------------- docs


def docs_map():
    docs = [f for f in FILES if f.endswith(".md")]
    classified = defaultdict(list)
    for f in docs:
        cls = next((c for c, pattern in DOC_RULES if fnmatch.fnmatch(f, pattern)), None)
        if cls is None:
            ERRORS.append(f"{f}: unclassified markdown file; add a rule to DOC_RULES in fork/tools/gen_maps.py")
        classified[cls or "?"].append(f)
    out = ["# 文档地图\n\n", NOTICE]
    out.append(
        "每个已跟踪的 `.md` 文件按路径规则归为一类（规则在 `fork/tools/gen_maps.py` 的 `DOC_RULES` 中，先匹配者优先）。"
        "上游的用户文档目录是 `docs/`（目录页 `docs/index.md`）；fork 文档的入口是 [fork/README.md](../../README.md)。\n\n"
    )
    rows = [[c, DOC_CLASSES.get(c, "未分类"), len(classified[c])] for c in sorted(classified)]
    out += [table(["类", "含义", "文件数"], rows), "\n"]
    for c in sorted(classified):
        out += [f"## {c}：{DOC_CLASSES.get(c, '未分类')}\n\n", "".join(f"- `{f}`\n" for f in classified[c]), "\n"]
    return "".join(out).rstrip("\n") + "\n"


