def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the generated files")
    mode.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = parser.parse_args()

    python_md, module_count = python_map()
    native_md, target_count = native_map()
    outputs = dict(zip(OUTPUTS, [python_md, native_md, tests_map(), docs_map(), ledger_readme()]))
    stale = []
    for path, content in outputs.items():
        target = ROOT / path
        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
        elif not target.exists() or target.read_text(encoding="utf-8") != content:
            stale.append(path)
    print(f"gen_maps: {module_count} Python modules, {target_count} CMake target definitions, {len(outputs)} files")
    for error in ERRORS:
        print(f"  {error}")
    for path in stale:
        print(f"  out of date: {path} (run fork/dev map)")
    return 1 if ERRORS or stale else 0


if __name__ == "__main__":
    sys.exit(main())
