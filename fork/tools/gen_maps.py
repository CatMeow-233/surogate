def text(path):
    if path not in _text:
        _text[path] = (ROOT / path).read_text(encoding="utf-8", errors="replace")
    return _text[path]


def required(path):
    """Text of an upstream file parsed by a fixed path; an error rather than a traceback when it is gone."""
    if not (ROOT / path).is_file():
        ERRORS.append(f"{path}: not found; upstream moved or deleted it, update the path in fork/tools/gen_maps.py")
        return ""
    return text(path)


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def tick(value):
    return f"`{value}`"


def call_text(path, start):
    """Text of the CMake call whose '(' is at or after start, up to the matching ')'."""
    src = text(path)
    depth, i = 0, src.index("(", start)
    for j in range(i, len(src)):
        depth += {"(": 1, ")": -1}.get(src[j], 0)
        if depth == 0:
            return src[i + 1 : j]
    return src[i + 1 :]


def cmake_tokens(call):
    return re.sub(r"#[^\n]*", "", call).split()


